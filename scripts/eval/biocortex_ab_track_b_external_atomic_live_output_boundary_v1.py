def _field_profile(name: str, source: str, stage: str) -> dict[str, Any]:
    if name.endswith("_SHA256") or name in {"CHALLENGE", "OPERATION_ID"}:
        encoding, minimum, maximum = "LOWER_HEX", 64, 64
        extras = {
            "comparison_semantics": "BYTE_EXACT",
            "pattern": "^[0-9a-f]{64}$",
        }
    elif name in {
        "INVOCATION_SLOT",
        "EXPECTED_AUTHORITY_EPOCH",
        "MIN_LEADER_TERM",
        "MIN_COMMITTED_REVISION",
        "ACTUAL_AUTHORITY_EPOCH",
        "ACTUAL_LEADER_TERM",
        "ACTUAL_COMMITTED_REVISION",
        "RECORD_SEQUENCE",
        "LOGICAL_SINK_FENCE",
        "SIGNER_KEY_VERSION",
        "ACTUAL_SIGNER_KEY_VERSION",
    }:
        encoding, minimum, maximum = "CANONICAL_UNSIGNED_DECIMAL_ASCII", 1, 20
        extras = {
            "comparison_semantics": "ARBITRARY_PRECISION_UNSIGNED_INTEGER",
            "pattern": "^(0|[1-9][0-9]*)$",
        }
    elif name == "AUTHORITY_STATE":
        encoding, minimum, maximum = "UTF8_NFC_TOKEN", 1, 64
        extras = {
            "comparison_semantics": "UTF8_NFC_BYTE_EXACT",
            "enum": list(AUTHORITY_STATE_VALUES),
            "pattern": "^[A-Z][A-Z0-9_]{0,63}$",
        }
    elif name == "SIGNER_KMS_RESOURCE_ID":
        encoding, minimum, maximum = "UTF8_NFC_TOKEN", 1, 512
        extras = {
            "comparison_semantics": "UTF8_NFC_BYTE_EXACT",
            "pattern": "^[^\\u0000-\\u001f\\u007f]{1,512}$",
        }
    else:
        encoding, minimum, maximum = "UTF8_NFC_TOKEN", 1, 192
        extras = {
            "comparison_semantics": "UTF8_NFC_BYTE_EXACT",
            "pattern": "^[^\\u0000-\\u001f\\u007f]{1,192}$",
        }
    profile = {
        "encoding": encoding,
        "max_length": maximum,
        "min_length": minimum,
        "name": name,
        "source": source,
        "stage": stage,
        "type": "string",
    }
    profile.update(extras)
    return profile


