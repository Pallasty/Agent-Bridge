SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
UTC_RE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$")


class BoundaryError(ValueError):
    """Closed-contract validation failure."""


def _fail(code: str, detail: str) -> None:
    raise BoundaryError(f"{code}: {detail}")


def _require(condition: bool, code: str, detail: str) -> None:
    if not condition:
        _fail(code, detail)


def _reject_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    value: dict[str, Any] = {}
    for key, item in pairs:
        if key in value:
            _fail("DUPLICATE_KEY", key)
        value[key] = item
    return value


def _depth(value: Any, level: int = 0) -> int:
    _require(level <= MAX_JSON_DEPTH, "JSON_DEPTH", "maximum nesting exceeded")
    if isinstance(value, dict):
        for item in value.values():
            _depth(item, level + 1)
    elif isinstance(value, list):
        for item in value:
            _depth(item, level + 1)
    return level


def canonical_bytes(value: Any) -> bytes:
    try:
        raw = (
            json.dumps(
                value,
                ensure_ascii=False,
                allow_nan=False,
                sort_keys=True,
                indent=2,
                separators=(",", ": "),
            )
            + "\n"
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        _fail("CANONICAL_JSON", str(exc))
    _require(len(raw) <= MAX_CANONICAL_BYTES, "CANONICAL_SIZE", "document too large")
    return raw


def parse_canonical_object(raw: bytes, label: str) -> dict[str, Any]:
    _require(len(raw) <= MAX_CANONICAL_BYTES, "INPUT_SIZE", label)
    try:
        value = json.loads(
            raw.decode("utf-8"),
            parse_constant=lambda token: _fail("NONFINITE", f"{label}:{token}"),
            object_pairs_hook=_reject_pairs,
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        _fail("JSON_PARSE", f"{label}:{exc}")
    _require(type(value) is dict, "ROOT_TYPE", f"{label} must be an object")
    _depth(value)
    _require(canonical_bytes(value) == raw, "CANONICAL_BYTES", label)
    return value


def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _exact_keys(value: Any, expected: tuple[str, ...], code: str) -> None:
    _require(type(value) is dict, code, "object required")
    _require(tuple(sorted(value)) == tuple(sorted(expected)), code, "closed key set drift")


def _valid_utc(value: Any, code: str) -> None:
    _require(type(value) is str and UTC_RE.fullmatch(value) is not None, code, "UTC shape")
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    except ValueError as exc:
        _fail(code, str(exc))
    _require(parsed.strftime("%Y-%m-%dT%H:%M:%SZ") == value, code, "UTC canonical")


def _valid_sha256(value: Any, code: str) -> None:
    _require(type(value) is str and SHA256_RE.fullmatch(value) is not None, code, "SHA-256 shape")
    _require(value != "0" * 64, code, "zero digest")


def reconstruct_signature_message(authority_decision_sha256: str) -> bytes:
    _require(
        type(authority_decision_sha256) is str
        and SHA256_RE.fullmatch(authority_decision_sha256) is not None,
        "SIGNATURE_MESSAGE_DIGEST",
        "authority decision digest must be canonical lower-hex SHA-256",
    )
    payload = bytes.fromhex(authority_decision_sha256)
    _require(
        len(payload) == 32,
        "SIGNATURE_MESSAGE_PAYLOAD_LENGTH",
        "decoded authority decision digest must be 32 bytes",
    )
    try:
        domain = SIGNATURE_MESSAGE_CONTRACT["domain_tag"].encode("ascii")
    except UnicodeEncodeError as exc:
        _fail("SIGNATURE_MESSAGE_DOMAIN", str(exc))
    message = (
        len(domain).to_bytes(4, "big")
        + domain
        + len(payload).to_bytes(8, "big")
        + payload
    )
    _require(
        len(domain) == SIGNATURE_MESSAGE_CONTRACT["domain_tag_bytes"]
        and len(message) == SIGNATURE_MESSAGE_CONTRACT["expected_message_bytes"],
        "SIGNATURE_MESSAGE_LENGTH",
        "domain or framed message length drift",
    )
    return message


def canonical_authority_decision_payload_bytes(payload: dict[str, Any]) -> bytes:
    _exact_keys(
        payload,
        AUTHORITY_DECISION_PAYLOAD_FIELDS,
        "AUTHORITY_DECISION_PAYLOAD_KEYS",
    )
    profiles = {
        item["name"]: item
        for item in RESULT_FIELD_PROFILES
        if item["name"] in AUTHORITY_DECISION_PAYLOAD_FIELDS
    }
    _require(
        tuple(profiles) == AUTHORITY_DECISION_PAYLOAD_FIELDS,
        "AUTHORITY_DECISION_PAYLOAD_PROFILES",
        "payload field profile order drift",
    )
    for name in AUTHORITY_DECISION_PAYLOAD_FIELDS:
        value = payload[name]
        profile = profiles[name]
        _require(type(value) is str, "AUTHORITY_DECISION_PAYLOAD_TYPE", name)
        _require(
            profile["min_length"] <= len(value) <= profile["max_length"],
            "AUTHORITY_DECISION_PAYLOAD_LENGTH",
            name,
        )
        _require(
            re.fullmatch(profile["pattern"], value) is not None,
            "AUTHORITY_DECISION_PAYLOAD_PATTERN",
            name,
        )
        if "enum" in profile:
            _require(
                value in profile["enum"],
                "AUTHORITY_DECISION_PAYLOAD_ENUM",
                name,
            )
    raw = canonical_bytes(payload)
    _require(
        len(raw) <= AUTHORITY_DECISION_CONTRACT["max_canonical_bytes"],
        "AUTHORITY_DECISION_PAYLOAD_SIZE",
        "payload exceeds closed contract maximum",
    )
    return raw


