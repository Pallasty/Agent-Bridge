def validate_contract(contract: dict[str, Any]) -> None:
    expected = build_contract_document()
    _require(contract == expected, "CONTRACT_DRIFT", "closed contract differs from v1")
    grain = contract["authority_grain"]
    _require(
        "OPERATION_ID" not in grain["operation_id_derivation"]["input_bindings"],
        "OPERATION_ID_SELF_REFERENCE",
        "operation id must not hash itself",
    )
    _require(
        tuple(item["name"] for item in grain["request_envelope"]["fields"])
        == REQUEST_IDENTITY_BINDINGS,
        "REQUEST_FIELD_ORDER",
        "request field drift",
    )
    _require(
        tuple(item["name"] for item in grain["result_envelope"]["fields"])
        == RESULT_BINDINGS,
        "RESULT_FIELD_ORDER",
        "result field drift",
    )
    _require(
        "AUTHORITY_STATE" in RESULT_BINDINGS
        and "ACTUAL_SIGNER_KEY_VERSION" in RESULT_BINDINGS
        and "SIGNER_KEY_VERSION" not in RESULT_BINDINGS,
        "RESULT_AUTHORITY_BINDINGS",
        "result must expose authority state and an unambiguous actual signer version",
    )
    decision_contract = grain["authority_decision_payload_contract"]
    _require(
        tuple(decision_contract["field_names"])
        == AUTHORITY_DECISION_PAYLOAD_FIELDS
        and tuple(
            item["name"] for item in decision_contract["field_profiles"]
        )
        == AUTHORITY_DECISION_PAYLOAD_FIELDS,
        "AUTHORITY_DECISION_FIELDS",
        "authority decision payload field closure drift",
    )
    _require(
        decision_contract["excluded_result_fields"]
        == ["AUTHORITY_DECISION_SHA256", "SIGNATURE_RECEIPT_SHA256"]
        and not set(decision_contract["field_names"])
        .intersection(decision_contract["excluded_result_fields"]),
        "AUTHORITY_DECISION_CYCLE",
        "authority decision digest and signature receipt must be excluded",
    )
    _require(
        decision_contract["request_envelope_resolution_rule"]
        == AUTHORITY_DECISION_CONTRACT["request_envelope_resolution_rule"],
        "AUTHORITY_DECISION_REQUEST_RESOLUTION",
        "authority decision must resolve and validate its exact request envelope",
    )
    result_projection = tuple(
        name
        for name in RESULT_BINDINGS
        if name not in decision_contract["excluded_result_fields"]
    )
    _require(
        result_projection == AUTHORITY_DECISION_PAYLOAD_FIELDS
        and decision_contract["result_projection_rule"]
        == AUTHORITY_DECISION_CONTRACT["result_projection_rule"],
        "AUTHORITY_DECISION_RESULT_PROJECTION",
        "signed payload must be the exact byte-equal projection of final result fields",
    )
    decision_kat = decision_contract["known_answer_test"]
    decision_bytes = canonical_authority_decision_payload_bytes(
        decision_kat["payload"]
    )
    _require(
        len(decision_bytes) == decision_kat["payload_canonical_bytes"]
        and sha256_bytes(decision_bytes) == decision_kat["payload_sha256"],
        "AUTHORITY_DECISION_KAT",
        "authority decision transcript known-answer test drift",
    )
    _require(
        tuple(
            item["name"]
            for item in grain["signature_receipt_contract"]["fields"]
        )
        == tuple(item["name"] for item in SIGNATURE_RECEIPT_FIELDS),
        "SIGNATURE_RECEIPT_FIELDS",
        "signature receipt field drift",
    )
    receipt_contract = grain["signature_receipt_contract"]
    _require(
        receipt_contract["canonicalization"]
        == "RFC8785_COMPATIBLE_RESTRICTED_CANONICAL_JSON_PROFILE_V1"
        and receipt_contract["duplicate_key_policy"]
        == "REJECT_BEFORE_CANONICALIZATION"
        and receipt_contract["max_canonical_bytes"] == 65536
        and receipt_contract["receipt_hash_rule"]
        == "SIGNATURE_RECEIPT_SHA256_EQUALS_LOWER_HEX_SHA256_OF_EXACT_CANONICAL_RECEIPT_BYTES",
        "SIGNATURE_RECEIPT_CANONICAL_HASH",
        "signature receipt content hash must use one closed canonical profile",
    )
    _require(
        receipt_contract["key_binding"] == SIGNATURE_KEY_BINDING_CONTRACT,
        "SIGNATURE_KEY_BINDING",
        "exact signer resource or raw public-key binding drift",
    )
    _require(
        receipt_contract["message_derivation"] == SIGNATURE_MESSAGE_CONTRACT,
        "SIGNATURE_MESSAGE_CONTRACT",
        "signature message derivation drift",
    )
    receipt_field_names = tuple(item["name"] for item in receipt_contract["fields"])
    _require(
        "SIGNED_MESSAGE_SHA256" in receipt_field_names
        and "SIGNED_PAYLOAD_SHA256" not in receipt_field_names,
        "SIGNATURE_MESSAGE_FIELD",
        "receipt must identify the exact framed message, not an ambiguous payload",
    )
    known_answer = receipt_contract["message_derivation"]["known_answer_test"]
    known_message = reconstruct_signature_message(
        known_answer["authority_decision_sha256"]
    )
    _require(
        known_message.hex() == known_answer["message_hex"]
        and sha256_bytes(known_message) == known_answer["message_sha256"],
        "SIGNATURE_MESSAGE_KAT",
        "signature message known-answer test drift",
    )
    state_machine = contract["state_machine"]
    _require(
        tuple(state_machine["physical_sink_terminal_fence_states"])
        == PHYSICAL_SINK_FENCE_STATES,
        "SINK_FENCE_STATES",
        "terminal sink fence state drift",
    )
    fence_contract = state_machine["physical_sink_terminal_fence"]
    _require(
        fence_contract["global_cas_claimed"] is False
        and fence_contract["authority_and_sink_fence_share_transaction"] is False
        and fence_contract["unfence_allowed"] is False,
        "SINK_FENCE_BOUNDARY",
        "sink fence must remain same-domain, absorbing, and non-global",
    )
    vectors = state_machine["terminal_authority_sink_vectors"]
    vector_pairs = [
        (item["authority_state"], item["physical_sink_state"])
        for item in vectors
    ]
    expected_pairs = [
        (authority, sink)
        for authority in AUTHORITY_TERMINAL_STATES
        for sink in PHYSICAL_SINK_PERSISTENT_STATES
    ]
    _require(
        vector_pairs == expected_pairs and len(set(vector_pairs)) == 16,
        "TERMINAL_VECTOR_COVERAGE",
        "terminal authority by sink Cartesian product must be exact and ordered",
    )
    visible_vectors = [
        item
        for item in vectors
        if item["reviewer_visibility"] != "PERMANENTLY_FORBIDDEN"
    ]
    _require(
        len(visible_vectors) == 1
        and visible_vectors[0]["authority_state"] == "SEALED_OBSERVED"
        and visible_vectors[0]["physical_sink_state"] == "SEALED"
        and visible_vectors[0]["reviewer_visibility"]
        == "POST_GENERATION_MAP_GATE_ONLY",
        "TERMINAL_VECTOR_VISIBILITY",
        "only sealed-observed by sealed may reach the later map gate",
    )
    for item in vectors:
        _require(
            item["required_fence_state"] == "TERMINAL_AUTHORITY_FENCED"
            and item["authority_action"] == "PRESERVE_ABSORBING_TERMINAL"
            and item["sink_action"] == "READ_ONLY_AFTER_FENCE",
            "TERMINAL_VECTOR_ACTION",
            "terminal vectors must preserve authority and freeze the sink",
        )
        if item["authority_state"] in {
            "BURNED_EMPTY",
            "PARTIAL_QUARANTINED",
            "AMBIGUOUS_QUARANTINED",
        }:
            _require(
                item["reviewer_visibility"] == "PERMANENTLY_FORBIDDEN",
                "TERMINAL_VECTOR_QUARANTINE_VISIBILITY",
                "burned or quarantine authority must dominate every sink state",
            )
    transitions = state_machine["transitions"]
    mutating_operations = set(
        fence_contract[
            "mutating_operations_requiring_open_fence_in_same_sink_linearization"
        ]
    )
    for item in transitions:
        expected_scope = (
            "PHYSICAL_SINK_RECORD_ONLY"
            if item["domain"] == "PHYSICAL_SINK"
            else "AUTHORITY_DATABASE_ONLY"
        )
        _require(
            item["atomic_precondition_scope"] == expected_scope,
            "TRANSITION_ATOMIC_SCOPE",
            item["operation"],
        )
        if item["operation"] in mutating_operations:
            _require(
                "OPEN" in item["atomic_precondition"]
                and item["linearization"]
                in {
                    "EXACT_PRE_STATE_PHYSICAL_SINK_CAS",
                    "EXACT_PRE_STATE_PHYSICAL_SINK_RECORD_CAS",
                },
                "SINK_MUTATION_FENCE",
                item["operation"],
            )
    absent_fence_transition = next(
        item
        for item in transitions
        if item["operation"]
        == fence_contract["terminal_fence_absent_record_operation"]
    )
    _require(
        absent_fence_transition["domain"] == "PHYSICAL_SINK"
        and absent_fence_transition["atomic_precondition_scope"]
        == "PHYSICAL_SINK_RECORD_ONLY"
        and absent_fence_transition["atomic_precondition"]
        == "SINK_RECORD_IS_ABSENT_FOR_EXACT_OPERATION_AND_SLOT"
        and absent_fence_transition["cross_domain_observation_nonatomic"]
        == "VERIFIED_SIGNED_AUTHORITY_DECISION_PAYLOAD_HAS_TERMINAL_STATE_AND_EXACT_BINDINGS_NONATOMIC"
        and absent_fence_transition["next_authority_state"] == "UNCHANGED"
        and absent_fence_transition["next_sink_state"] == "EMPTY"
        and absent_fence_transition["next_sink_fence_state"]
        == "TERMINAL_AUTHORITY_FENCED"
        and absent_fence_transition["linearization"]
        == "EXACT_ABSENT_PHYSICAL_SINK_RECORD_CAS_CREATE",
        "SINK_FENCE_ABSENT_TRANSITION",
        "an absent sink record must become an empty terminal-fenced record",
    )
    existing_fence_transition = next(
        item
        for item in transitions
        if item["operation"]
        == fence_contract["terminal_fence_existing_record_operation"]
    )
    _require(
        existing_fence_transition["domain"] == "PHYSICAL_SINK"
        and existing_fence_transition["atomic_precondition_scope"]
        == "PHYSICAL_SINK_RECORD_ONLY"
        and existing_fence_transition["atomic_precondition"]
        == "SINK_RECORD_MATCHES_OPERATION_LOGICAL_FENCE_OPEN_AND_ANY_OUTPUT_STATE"
        and existing_fence_transition["cross_domain_observation_nonatomic"]
        == "VERIFIED_SIGNED_AUTHORITY_DECISION_PAYLOAD_HAS_TERMINAL_STATE_AND_EXACT_BINDINGS_NONATOMIC"
        and existing_fence_transition["next_authority_state"] == "UNCHANGED"
        and existing_fence_transition["next_sink_state"] == "UNCHANGED"
        and existing_fence_transition["next_sink_fence_state"]
        == "TERMINAL_AUTHORITY_FENCED"
        and existing_fence_transition["linearization"]
        == "EXACT_PRE_STATE_PHYSICAL_SINK_RECORD_CAS",
        "SINK_FENCE_EXISTING_TRANSITION",
        "an existing sink record must install its terminal fence in-place",
    )
    initialization_transition = next(
        item
        for item in transitions
        if item["operation"] == fence_contract["initialization_operation"]
    )
    _require(
        initialization_transition["domain"] == "PHYSICAL_SINK"
        and initialization_transition["atomic_precondition"]
        == "SINK_RECORD_IS_ABSENT_FOR_EXACT_OPERATION_AND_SLOT"
        and initialization_transition["next_sink_state"] == "EMPTY"
        and initialization_transition["next_sink_fence_state"] == "OPEN"
        and initialization_transition["linearization"]
        == "EXACT_ABSENT_PHYSICAL_SINK_RECORD_CAS_CREATE",
        "SINK_INITIALIZATION_TRANSITION",
        "physical sink record must be initialized by its own same-domain CAS",
    )
    authorize_transition = next(
        item
        for item in transitions
        if item["operation"] == "AUTHORIZE_CONSUME_AND_RESERVE_LOGICAL_SINK"
    )
    _require(
        authorize_transition["next_sink_state"] == "UNCHANGED"
        and authorize_transition["next_sink_fence_state"] == "UNCHANGED",
        "AUTHORITY_TRANSITION_SINK_EFFECT",
        "authority transaction must not initialize physical sink state",
    )
    operation_profile = next(
        item
        for item in grain["result_envelope"]["fields"]
        if item["name"] == "OPERATION_ID"
    )
    _require(
        operation_profile["encoding"] == "LOWER_HEX"
        and operation_profile["pattern"] == "^[0-9a-f]{64}$",
        "OPERATION_ID_ENCODING",
        "operation id must be lower-hex SHA-256",
    )


def validate_observation(observation: dict[str, Any]) -> None:
    expected = build_source_profile_observation()
    _require(observation == expected, "OBSERVATION_DRIFT", "closed observation differs from source profile")
    _valid_utc(observation["observed_at_utc"], "OBSERVED_AT")
    _require(
        observation["absence_claim_scope_qualified"] is True
        and observation["external_organization_state_observed"] is False
        and observation["host_visibility_complete"] is False,
        "OBSERVATION_SCOPE",
        "absence must remain scope-qualified",
    )


def build_design_receipt(
    contract_raw: bytes,
    observation_raw: bytes,
    *,
    evaluated_at_utc: str,
    boundary_source_sha256: str,
    observation_schema_sha256: str,
    receipt_schema_sha256: str,
    predecessor_guard_manifest_sha256: str,
    predecessor_s12_contract_sha256: str,
) -> dict[str, Any]:
    contract = parse_canonical_object(contract_raw, "boundary contract")
    observation = parse_canonical_object(observation_raw, "provider observation")
    validate_contract(contract)
    validate_observation(observation)
    _valid_utc(evaluated_at_utc, "EVALUATED_AT")
    _require(evaluated_at_utc >= observation["observed_at_utc"], "TIME_ORDER", "evaluation precedes observation")
    for code, value in (
        ("BOUNDARY_SOURCE_SHA", boundary_source_sha256),
        ("OBSERVATION_SCHEMA_SHA", observation_schema_sha256),
        ("RECEIPT_SCHEMA_SHA", receipt_schema_sha256),
        ("GUARD_MANIFEST_SHA", predecessor_guard_manifest_sha256),
        ("S12_CONTRACT_SHA", predecessor_s12_contract_sha256),
    ):
        _valid_sha256(value, code)

    receipt = {
        "all_generator_paths_guarded_verified": False,
        "anti_rollback_witness_verified": False,
        "authority_envelopes_frozen": True,
        "blockers": [f"{code}_UNBOUND_OR_UNVERIFIED" for code, _ in PREREQUISITES],
        "boundary_source_sha256": boundary_source_sha256,
        "caller_supplied_identity_digest_shapes_validated": True,
        "condition_output_authorized": False,
        "contract_sha256": sha256_bytes(contract_raw),
        "crash_cut_operational_evidence_verified": False,
        "crash_protocol_frozen": True,
        "custodian_trust_pin_verified": False,
        "decision": DECISION,
        "design_receipt_schema_sha256": receipt_schema_sha256,
        "evaluated_at_utc": evaluated_at_utc,
        "external_global_single_use_verified": False,
        "external_linearizable_authorize_consume_logical_sink_reservation_verified": False,
        "first_byte_cas_and_durability_verified": False,
        "guard_owned_sink_verified": False,
        "independent_fault_evidence_verified": False,
        "live_output_capability_emitted": False,
        "live_output_permit_defined": False,
        "loaded_runtime_attestation_verified": False,
        "non_bypassable_generator_runtime_verified": False,
        "on_disk_artifact_identity_verified": False,
        "owner_trust_pin_verified": False,
        "predecessor_guard_manifest_sha256": predecessor_guard_manifest_sha256,
        "predecessor_s12_contract_sha256": predecessor_s12_contract_sha256,
        "prerequisite_schema_frozen": True,
        "prerequisite_verification": _evidence_rows(),
        "private_single_use_capability_verified": False,
        "production_provider_bound_and_verified": False,
        "provider_prerequisite_observation_schema_sha256": observation_schema_sha256,
        "readiness_observation_sha256": sha256_bytes(observation_raw),
        "receipt_is_output_permit": False,
        "schema": RECEIPT_SCHEMA,
        "schema_and_internal_consistency_verified": True,
        "side_effects_unlocked": "NONE",
        "state_machine_frozen": True,
        "status": STATUS,
        "trusted_currentness_at_use_verified": False,
        "version": 1,
    }
    validate_receipt(receipt)
    return receipt


def validate_receipt(receipt: dict[str, Any]) -> None:
    expected_keys = (
        "all_generator_paths_guarded_verified",
        "anti_rollback_witness_verified",
        "authority_envelopes_frozen",
        "blockers",
        "boundary_source_sha256",
        "caller_supplied_identity_digest_shapes_validated",
        "condition_output_authorized",
        "contract_sha256",
        "crash_cut_operational_evidence_verified",
        "crash_protocol_frozen",
        "custodian_trust_pin_verified",
        "decision",
        "design_receipt_schema_sha256",
        "evaluated_at_utc",
        "external_global_single_use_verified",
        "external_linearizable_authorize_consume_logical_sink_reservation_verified",
        "first_byte_cas_and_durability_verified",
        "guard_owned_sink_verified",
        "independent_fault_evidence_verified",
        "live_output_capability_emitted",
        "live_output_permit_defined",
        "loaded_runtime_attestation_verified",
        "non_bypassable_generator_runtime_verified",
        "on_disk_artifact_identity_verified",
        "owner_trust_pin_verified",
        "predecessor_guard_manifest_sha256",
        "predecessor_s12_contract_sha256",
        "prerequisite_schema_frozen",
        "prerequisite_verification",
        "private_single_use_capability_verified",
        "production_provider_bound_and_verified",
        "provider_prerequisite_observation_schema_sha256",
        "readiness_observation_sha256",
        "receipt_is_output_permit",
        "schema",
        "schema_and_internal_consistency_verified",
        "side_effects_unlocked",
        "state_machine_frozen",
        "status",
        "trusted_currentness_at_use_verified",
        "version",
    )
    _exact_keys(receipt, expected_keys, "RECEIPT_KEYS")
    _require(receipt["schema"] == RECEIPT_SCHEMA, "RECEIPT_SCHEMA", "schema drift")
    _require(receipt["version"] == 1, "RECEIPT_VERSION", "version drift")
    _require(receipt["decision"] == DECISION, "RECEIPT_DECISION", "decision drift")
    _require(receipt["status"] == STATUS, "RECEIPT_STATUS", "status drift")
    _require(
        receipt["blockers"] == [
            f"{code}_UNBOUND_OR_UNVERIFIED" for code, _ in PREREQUISITES
        ],
        "RECEIPT_BLOCKERS",
        "blocker drift",
    )
    _require(
        receipt["prerequisite_verification"] == _evidence_rows(),
        "RECEIPT_PREREQUISITES",
        "prerequisite matrix drift",
    )
    _valid_utc(receipt["evaluated_at_utc"], "RECEIPT_TIME")
    for key in (
        "boundary_source_sha256",
        "contract_sha256",
        "design_receipt_schema_sha256",
        "predecessor_guard_manifest_sha256",
        "predecessor_s12_contract_sha256",
        "provider_prerequisite_observation_schema_sha256",
        "readiness_observation_sha256",
    ):
        _valid_sha256(receipt[key], f"RECEIPT_{key.upper()}")
    for key in (
        "authority_envelopes_frozen",
        "caller_supplied_identity_digest_shapes_validated",
        "crash_protocol_frozen",
        "prerequisite_schema_frozen",
        "schema_and_internal_consistency_verified",
        "state_machine_frozen",
    ):
        _require(receipt[key] is True, "RECEIPT_TRUE", key)
    for key in (
        "all_generator_paths_guarded_verified",
        "anti_rollback_witness_verified",
        "condition_output_authorized",
        "crash_cut_operational_evidence_verified",
        "custodian_trust_pin_verified",
        "external_global_single_use_verified",
        "external_linearizable_authorize_consume_logical_sink_reservation_verified",
        "first_byte_cas_and_durability_verified",
        "guard_owned_sink_verified",
        "independent_fault_evidence_verified",
        "live_output_capability_emitted",
        "live_output_permit_defined",
        "loaded_runtime_attestation_verified",
        "non_bypassable_generator_runtime_verified",
        "on_disk_artifact_identity_verified",
        "owner_trust_pin_verified",
        "private_single_use_capability_verified",
        "production_provider_bound_and_verified",
        "receipt_is_output_permit",
        "trusted_currentness_at_use_verified",
    ):
        _require(receipt[key] is False, "RECEIPT_FALSE", key)
    _require(receipt["side_effects_unlocked"] == "NONE", "RECEIPT_SIDE_EFFECTS", "side effects forbidden")


